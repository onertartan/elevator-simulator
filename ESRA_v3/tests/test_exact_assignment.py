"""Small, exhaustive checks for the *Python* destination/WT assignment model.

The golden vector was evaluated with the unrefactored objective on 2026-09-26,
before extracting its per-car calculation. It is not generated by the helper
under test. Run: python tests/test_exact_assignment.py
"""
